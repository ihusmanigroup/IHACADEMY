/**
 * Regenerates admin/src/data/internTaskMeta.js from the client-side assignment
 * catalog (single source of truth: client/src/data/internAssignmentsData.js).
 * Run with: node scripts/gen-intern-task-meta.mjs
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { assignmentById, ALL_TRACKS, trackStats } from '../client/src/data/internAssignmentsData.js'

const __dirname = dirname(fileURLToPath(import.meta.url))
const outPath = join(__dirname, '..', 'admin', 'src', 'data', 'internTaskMeta.js')

const titles = {}
const meta = {}
const rubric = {}

for (const [id, a] of Object.entries(assignmentById)) {
  titles[id] = a.title
  meta[id] = {
    week: a.weekLabel,
    weekNum: a.weekNumber,
    track: a.track,
    trackId: a.trackId,
    type: a.type,
    slug: a.slug,
    stableKey: a.stableKey,
  }
  rubric[id] = a.rubric.map((r) => ({ criterion: r.criterion, maxScore: r.maxScore }))
}

const tracks = trackStats().map((t) => ({ slug: t.slug, label: t.label }))

const header = `/**
 * AUTO-GENERATED by scripts/gen-intern-task-meta.mjs — do not edit manually.
 * Mirrors client/src/data/internAssignmentsData.js so the admin panel can
 * label live intern submissions with catalog titles, weeks, tracks and rubrics.
 * Regenerate after catalog changes: node scripts/gen-intern-task-meta.mjs
 */
`

const body = `export const INTERN_TASK_TITLES = ${JSON.stringify(titles, null, 2)}

export const INTERN_TASK_META = ${JSON.stringify(meta, null, 2)}

export const ASSIGNMENT_RUBRIC = ${JSON.stringify(rubric, null, 2)}

export const INTERN_TRACKS = ${JSON.stringify(tracks, null, 2)}

export const ALL_TRACKS_LABELS = ${JSON.stringify(ALL_TRACKS, null, 2)}

export function internTaskWeek(taskId) {
  const m = INTERN_TASK_META[taskId]
  return m ? m.week : \`Week \${Math.ceil(taskId / 5)}\`
}

export function internTaskTrack(taskId) {
  const m = INTERN_TASK_META[taskId]
  return m ? m.track : 'Unknown'
}
`

writeFileSync(outPath, header + body, 'utf8')
console.log(`Wrote ${outPath} (${Object.keys(titles).length} assignments, ${tracks.length} tracks)`)
